  let language = 'en';
  const menuButton = document.querySelector('.menu-toggle');
  const navigation = document.querySelector('.primary-nav');

  function translateAttribute(selector, attribute, keyAttribute) {
    document.querySelectorAll(selector).forEach((element) => {
      const value = copy[language][element.dataset[keyAttribute]];
      if (value) element.setAttribute(attribute, value);
    });
  }

  function closeMenu() {
    if (!menuButton || !navigation) return;
    menuButton.setAttribute('aria-expanded', 'false');
    navigation.classList.remove('open');
    menuButton.setAttribute('aria-label', copy[language]['menu.open']);
  }

  function setLanguage(nextLanguage) {
    language = copy[nextLanguage] ? nextLanguage : 'en';
    document.documentElement.lang = language;
    document.title = copy[language]['seo.title'];
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = copy[language]['seo.description'];

    document.querySelectorAll('[data-i18n]').forEach((element) => {
      const value = copy[language][element.dataset.i18n];
      if (value) element.innerHTML = value;
    });
    translateAttribute('[data-i18n-placeholder]', 'placeholder', 'i18nPlaceholder');
    translateAttribute('[data-i18n-alt]', 'alt', 'i18nAlt');
    translateAttribute('[data-i18n-aria]', 'aria-label', 'i18nAria');

    document.querySelectorAll('.lang-btn').forEach((button) => {
      const active = button.dataset.lang === language;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', String(active));
    });
    try { localStorage.setItem('sosa-language', language); } catch (_) { /* storage may be unavailable */ }
    closeMenu();
  }

  document.querySelectorAll('.lang-btn').forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.lang));
  });

  if (menuButton && navigation) {
    menuButton.addEventListener('click', () => {
      const isOpen = menuButton.getAttribute('aria-expanded') === 'true';
      menuButton.setAttribute('aria-expanded', String(!isOpen));
      navigation.classList.toggle('open', !isOpen);
      menuButton.setAttribute('aria-label', copy[language][isOpen ? 'menu.open' : 'menu.close']);
    });
    navigation.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
    document.addEventListener('keydown', (event) => {
      if (event.key === 'Escape') closeMenu();
    });
  }

  let savedLanguage = 'en';
  try { savedLanguage = localStorage.getItem('sosa-language') || 'en'; } catch (_) { /* storage may be unavailable */ }
  const requestedLanguage = new URLSearchParams(window.location.search).get('lang');
  setLanguage(requestedLanguage || savedLanguage);

  const header = document.querySelector('.site-header');
  function updateScroll() {
    const scrollable = document.documentElement.scrollHeight - window.innerHeight;
    const progress = scrollable > 0 ? Math.min(100, (window.scrollY / scrollable) * 100) : 0;
    document.documentElement.style.setProperty('--scroll-progress', `${progress}%`);
    if (header) header.classList.toggle('scrolled', window.scrollY > 24);
  }
  updateScroll();
  window.addEventListener('scroll', updateScroll, { passive: true });

  if (!window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    document.body.classList.add('motion-ready');
    const observer = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          observer.unobserve(entry.target);
        }
      });
    }, { rootMargin: '0px 0px -8% 0px', threshold: 0.08 });
    document.querySelectorAll('.reveal').forEach((element) => observer.observe(element));
  } else {
    document.querySelectorAll('.reveal').forEach((element) => element.classList.add('is-visible'));
  }

  const form = document.getElementById('contact-form');
  const formStartedAt = Date.now();
  if (form) {
    const query = new URLSearchParams(window.location.search);
    ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content'].forEach((name) => {
      const fromQuery = query.get(name);
      if (fromQuery) {
        try { sessionStorage.setItem(`sosa-${name}`, fromQuery); } catch (_) { /* storage may be unavailable */ }
      }
      let value = fromQuery || '';
      if (!value) {
        try { value = sessionStorage.getItem(`sosa-${name}`) || ''; } catch (_) { /* storage may be unavailable */ }
      }
      const input = form.elements.namedItem(name);
      if (input) input.value = value;
    });
    const landingPage = form.elements.namedItem('landing_page');
    if (landingPage) landingPage.value = window.location.href;

    let submitting = false;
    form.addEventListener('submit', async (event) => {
      event.preventDefault();
      if (submitting) return;

      const honeypot = form.elements.namedItem('botcheck');
      if ((honeypot && honeypot.checked) || Date.now() - formStartedAt < 3000) return;

      const requiredFields = [...form.querySelectorAll('[required]')];
      requiredFields.forEach((field) => field.removeAttribute('aria-invalid'));
      const invalid = requiredFields.filter((field) => !field.checkValidity());
      if (invalid.length) {
        invalid.forEach((field) => field.setAttribute('aria-invalid', 'true'));
        invalid[0].focus();
        return;
      }

      const submitButton = document.getElementById('contact-submit');
      submitting = true;
      if (submitButton) {
        submitButton.disabled = true;
        submitButton.textContent = copy[language]['form.sending'];
      }

      try {
        const response = await fetch(form.action, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
          body: JSON.stringify(Object.fromEntries(new FormData(form)))
        });
        const result = await response.json();
        if (!response.ok || !result.success) throw new Error('Submission failed');

        form.hidden = true;
        const success = document.getElementById('form-success');
        const successTitle = document.getElementById('success-title');
        const successMessage = document.getElementById('success-message');
        if (successTitle) successTitle.textContent = copy[language]['form.successTitle'];
        if (successMessage) successMessage.textContent = copy[language]['form.successMessage'];
        if (success) success.classList.add('show');
        if (typeof window.fbq === 'function') window.fbq('track', 'Lead');
      } catch (_) {
        const error = document.createElement('p');
        error.className = 'form-error';
        error.setAttribute('role', 'alert');
        error.textContent = copy[language]['form.error'];
        form.querySelector('.form-error')?.remove();
        form.appendChild(error);
      } finally {
        submitting = false;
        if (submitButton) {
          submitButton.disabled = false;
          submitButton.textContent = copy[language]['form.submit'];
        }
      }
    });
  }
